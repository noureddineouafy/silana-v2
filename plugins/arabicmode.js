function normalize(word) {
    return String(word || '')
        .replace(/[ً-ْـ]/g, '')
        .replace(/[إأآ]/g, 'ا')
        .replace(/ة/g, 'ه')
        .replace(/ى/g, 'ي')
        .trim()
        .toLowerCase()
}

