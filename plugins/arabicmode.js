var MAP = {}
var AR_OF = {}
for (var i = 0; i < PAIRS.length; i++) {
    MAP[normalize(PAIRS[i][0].replace(/ /g, '_'))] = PAIRS[i][1]
    MAP[normalize(PAIRS[i][0])] = PAIRS[i][1]
    if (!AR_OF[PAIRS[i][1]]) AR_OF[PAIRS[i][1]] = PAIRS[i][0]
}

var PREFIXES = ['.', '!', '/', '#']

function settings() {
    if (!global.db) global.db = { data: { settings: {} } }
    if (!global.db.data) global.db.data = { settings: {} }
    if (!global.db.data.settings) global.db.data.settings = {}
    if (!global.db.data.settings.arabicMode) global.db.data.settings.arabicMode = { off: {} }
    if (!global.db.data.settings.arabicMode.off) global.db.data.settings.arabicMode.off = {}
    return global.db.data.settings.arabicMode
}

function isOff(chatId) { return !!settings().off[chatId] }

function explainText(enCmd) {
    var e = EXPLAIN[enCmd]
    if (!e) return null
    var arName = AR_OF[enCmd] || e[0]
    return '📖 *شرح .' + arName.replace(/ /g, '_') + '* (.' + enCmd + ')\n\n' +
        '🔹 *شنو كيدير:*\n' + e[1] + '\n\n' +
        '🔹 *كيفاش تستعملو:*\n' + e[2] + '\n\n' +
        '💡 *مثال:* .' + (e[3] || arName.replace(/ /g, '_'))
}

function rewrite(m) {
    try {
        if (!m || typeof m.text !== 'string') return
        if (isOff(m.chat)) return
        var text = m.text
        if (text.length < 2) return
        var prefix = text.charAt(0)
        if (PREFIXES.indexOf(prefix) === -1) return
        var rest = text.slice(1)
        var match = rest.match(/^(\S+)([\s\S]*)$/)
        if (!match) return
        var word = match[1]
        var args = (match[2] || '').trim()
        // .شرح <cmd> -> explanation
        if (normalize(word) === normalize('شرح')) {
            var targetWord = args.split(/\s+/)[0]
            if (targetWord) m.text = prefix + 'arabicmode شرح ' + targetWord
            return
        }
        if (!/[؀-ۿ]/.test(word)) return
        var target = MAP[normalize(word.replace(/ /g, '_'))] || MAP[normalize(word)]
        if (!target) return
        if (target === 'arabicmode') { m.text = prefix + 'arabicmode list'; return }
        // .<arabic> شرح -> explain instead of run
        if (args === 'شرح' || args === '?' || args === 'مساعدة') {
            m.text = prefix + 'arabicmode شرح ' + word
            return
        }
        m.text = prefix + target + (match[2] || '')
    } catch (e) { /* a rewrite must never break the bot */ }
}

let handler = async (m, { conn, text, isOwner }) => {
    var arg = String(text || '').trim()
    var low = arg.toLowerCase()
    if (low === 'off' || low === 'on') {
        var allowed = !!isOwner
        if (!allowed && m.isGroup) {
            try {
                var meta = await conn.groupMetadata(m.chat)
                var me = (meta.participants || []).find(function (p) { return p.id === m.sender })
                allowed = !!(me && (me.admin === 'admin' || me.admin === 'superadmin'))
            } catch (e) { allowed = false }
        }
        if (!allowed) return m.reply('⛔ غير المالك ولا مشرفي المجموعة يقدرو يبدلو وضع الأوامر العربية.')
        var s = settings()
        if (low === 'off') s.off[m.chat] = true
        else delete s.off[m.chat]
        return m.reply(low === 'off'
            ? '🔴 وضع الأوامر العربية مطفي في هاد المحادثة. الأوامر بالإنجليزية خدامة كيف العادة.\nباش تعاود تشعلو: .arabicmode on'
            : '🟢 وضع الأوامر العربية مشعّل. كتب أي أمر بالعربية وغادي يخدم، مثال: .طقس مراكش')
    }
    if (arg.indexOf('شرح') === 0) {
        var wanted = arg.slice('شرح'.length).trim().split(/\s+/)[0] || ''
        if (!wanted) return m.reply('📖 كتب الأمر اللي بغيتي نشرحو ليك، مثال: .شرح طقس')
        var en = null
        if (EXPLAIN[wanted.toLowerCase()]) en = wanted.toLowerCase()
        else en = MAP[normalize(wanted.replace(/ /g, '_'))] || MAP[normalize(wanted)] || null
        if (en && explainText(en)) return m.reply(explainText(en))
        if (en) return m.reply('📖 .' + en + ' — هاد الميزة ما عنديش شرح مفصّل عليها باقي، ولكن الأمر خدام. شوف .arabicmode list للائحة كاملة.')
        return m.reply('❓ ما عرفتش هاد الأمر: «' + wanted + '».\nشوف اللائحة الكاملة بـ .arabicmode list، ولا جرّب .شرح + اسم الميزة بالعربية ولا بالإنجليزية.')
    }
    if (low === 'list' || arg === 'قائمة') {
        var lines = []
        var seen = {}
        for (var j = 0; j < PAIRS.length; j++) {
            var key = PAIRS[j][0] + '|' + PAIRS[j][1]
            if (seen[key]) continue
            seen[key] = true
            lines.push('.' + PAIRS[j][0].replace(/ /g, '_') + '  ←  .' + PAIRS[j][1])
        }
        var head = '🌍 *الأوامر العربية في سيلانا* (' + lines.length + ' أمر)\n' +
            'الوضع: ' + (isOff(m.chat) ? '🔴 مطفي هنا' : '🟢 مشعّل') + '\n' +
            'كتب الأمر بالعربية بنفس الطريقة، مثال: .طقس مراكش\n' +
            'وباش نشرح ليك أي ميزة مزيان: .شرح طقس ولا .طقس شرح\n\n'
        var chunk = head
        for (var k = 0; k < lines.length; k++) {
            if (chunk.length > 3200) { await m.reply(chunk); chunk = '' }
            chunk += lines[k] + '\n'
        }
        if (chunk) await m.reply(chunk)
        return
    }
    return m.reply(
        '🌍 *وضع الأوامر العربية*\n' +
        'الحالة هنا: ' + (isOff(m.chat) ? '🔴 مطفي' : '🟢 مشعّل') + '\n\n' +
        'مني يكون مشعّل، تقدر تكتب أوامر سيلانا بالعربية وغادي تخدم بحال الإنجليزية:\n' +
        '.طقس مراكش ← .weather\n.قائمة ← .menu\n.دبلجة ← .dub\n\n' +
        '📖 *الشرح المفصّل:* .شرح + اسم الميزة (مثال: .شرح دبلجة)، ولا زيد «شرح» بعد أي أمر عربي (مثال: .طقس شرح) وغادي نشرح ليك الميزة مزيان بلا ما تتنفذ.\n\n' +
        '.arabicmode list — لائحة الأوامر العربية كاملة\n' +
        '.arabicmode off / on — طفي ولا شعّل هنا (المالك/المشرفين)'
    )
}

handler.help = ['arabicmode']
