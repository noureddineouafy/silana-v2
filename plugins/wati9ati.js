async function showDoc(conn, m, usedPrefix, doc) {
    const body =
        `${doc.icon} *${doc.name}*\n\n` +
        `📍 *فين تمشي:*\n${doc.where}\n\n` +
        `🗂️ *الأوراق المطلوبة:*\n${doc.papers.map(p => '• ' + p).join('\n')}\n\n` +
        `💰 *الثمن:* ${doc.fees}\n` +
        `⏱️ *المدة:* ${doc.time}\n` +
        (doc.notes ? `📌 *ملاحظات:* ${doc.notes}\n` : '') +
        `\n⚠️ هاد المعلومات إرشادية عامة — تأكد من الأوراق والرسوم الحالية عند الإدارة قبل ما تمشي، حيت كتقدر تبدل.`
    return conn.reply(m.chat, body, m)
}

let handler = async (m, { conn, text, args, usedPrefix, command }) => {
    const arg = (args[0] || '').toLowerCase()
    const byKey = DOCS.find(d => d.key === arg)
    if (byKey) return showDoc(conn, m, usedPrefix, byKey)
    if (/^\d+$/.test(arg)) {
        const doc = DOCS[parseInt(arg) - 1]
        if (doc) return showDoc(conn, m, usedPrefix, doc)
        return conn.reply(m.chat, `⚠️ الرقم ما كاينش — اختار بين 1 و${DOCS.length} من .wati9ati`, m)
    }
    if (arg) {
        const hit = DOCS.find(d => d.name.includes((text || '').trim()))
        if (hit) return showDoc(conn, m, usedPrefix, hit)
    }
    const body =
        `🗂️ *وثيقتي — دليل الوثائق الإدارية المغربية*\n\n` +
        `اختار الوثيقة وبنوريك شنو خاصك تجيب وفين تمشي 👇\n\n` +
        DOCS.map((d, i) => `${i + 1}. ${d.icon} ${d.name}`).join('\n')
    const sections = [{
        title: 'الوثائق',
        rows: DOCS.map(d => ({ title: `${d.icon} ${d.name}`.slice(0, 24), description: 'اضغط لعرض الأوراق والمسطرة', id: `${usedPrefix}wati9ati ${d.key}` })),
    }]
    if (typeof conn.sendButton === 'function') {
        try {
            await conn.sendButton(m.chat, { text: body, footer: 'SILANA AI • وثيقتي', buttons: [{ name: 'single_select', buttonParamsJson: JSON.stringify({ title: 'اختر الوثيقة', sections }) }] }, { quoted: m })
            return
        } catch {}
    }
    return conn.reply(m.chat, body + `\n\nجاوب برقم الوثيقة: ${usedPrefix}wati9ati 1`, m)
}

handler.help = ['wati9ati']
handler.tags = ['morocco']
handler.command = ['wati9ati']
export default handler
      
